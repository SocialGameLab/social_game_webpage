"""Scaffold page copy for games recorded through social-game-env's `training` engine.

    uv run --project ../social_game_env python tools/new_env_games.py [--demo PATH] [--force]

For every game in social-game-env's ``demo/index.json`` whose engine is
``training`` (OpenSpiel games, puzzles, ...) and that has no
``content/games/<id>.yaml`` yet, writes one drawn with the ``moves`` kind and
adds the id to ``content/site.yaml``. The copy comes from the facts in the
recorded run's ``extras.about`` (players, information, chance, payoffs) and the
run itself (length, result, fallbacks), so run it after recording, then rebuild
with ``tools/build_data.py``. Hand-written files are never touched; ``--force``
rewrites the files this tool wrote that still start with ``GENERATED_MARK``.
Games without ``about`` facts, such as puzzles, are skipped: write those by hand.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "content"
GENERATED_MARK = "# Generated by tools/new_env_games.py"

_NUM = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six"}
_INFO = {
    "perfect_information": "Every player sees the whole state.",
    "imperfect_information": "Each player sees only its own view of the state, so part of it stays hidden from them.",
}
_CHANCE = {
    "deterministic": "There is no chance: the same moves always lead to the same state.",
    "explicit_stochastic": "Chance events such as deals or dice rolls are drawn from the run's seed.",
    "sampled_stochastic": "Chance events are sampled from the run's seed.",
}
_DYNAMICS = {
    "sequential": "The player to move picks one of the legal moves OpenSpiel lists for it.",
    "simultaneous": "Every player picks a move at the same time, and the moves resolve together.",
    "mean_field": "One representative agent picks a move for its population at each step.",
}
_UTILITY = {
    "zero_sum": ("zero-sum", "Returns sum to zero, so one player's gain is the others' loss."),
    "constant_sum": ("constant-sum", "Returns always add up to the same total."),
    "general_sum": ("general-sum", "Each player has its own return, so players can do well or badly together."),
    "identical": ("cooperative", "All players share one return, so they win or lose together."),
}


def _kind(about: dict[str, Any]) -> str:
    if about["players"] == 1 or about["dynamics"] == "mean_field":
        return "OpenSpiel · single player"
    return "OpenSpiel · perfect information" if about["information"] == "perfect_information" else "OpenSpiel · hidden information"


def _signed(v: float) -> str:
    return f"{'+' if v > 0 else ''}{v:g}"


def _outcome(rec: dict[str, Any]) -> str:
    res = rec["result"] or {}
    rewards = {int(s): v for s, v in (res.get("rewards") or {}).items()}
    returns = ", ".join(f"P{s} {_signed(v)}" for s, v in sorted(rewards.items()))
    if len(rewards) == 1:
        return f"a return of {_signed(rewards[0])}"
    if res.get("winners"):
        who = " and ".join(f"P{s}" for s in res["winners"])
        return f"{who} ahead ({returns})"
    return f"level returns ({returns})"


def content_for(gid: str, rec: dict[str, Any]) -> dict[str, Any]:
    about, ex = rec["about"], rec
    n = about["players"]
    short = rec["env_id"].split(":", 1)[1]
    params = ", ".join(f"`{k}={v}`" for k, v in sorted(about.get("params", {}).items()) if k != "players")
    pay_word, pay_line = _UTILITY.get(about["utility"], (about["utility"].replace("_", "-"), "Each player gets its own return."))
    players = "1 player" if n == 1 else f"{n} players"
    info_word = "no hidden information" if about["information"] == "perfect_information" else "hidden information"
    watch = [f"This run lasts {ex['turns']} move{'s' if ex['turns'] != 1 else ''} and ends with {_outcome(rec)}."]
    if ex["truncated"]:
        watch.append("It hit the 3000-move safety stop before the game ended.")
    watch.append(f"{ex['fallbacks']} move{'s' if ex['fallbacks'] != 1 else ''} fell back because the reply did not parse." if ex["fallbacks"]
                 else "Every move came from a parsed reply, with no fallbacks.")
    return {
        "id": gid,
        "title": about["long_name"],
        "kind": _kind(about),
        "players": f"{players} · {pay_word}",
        "tagline": f"{about['long_name']} from OpenSpiel: a {_NUM.get(n, n)}-player, {pay_word} game with {info_word}.",
        "view": "moves",
        "setup": [
            f"The game is OpenSpiel's `{short}`{f' with {params}' if params else ''}.",
            _INFO.get(about["information"], "Each player sees its own view of the state."),
            _CHANCE.get(about["chance"], "Chance events are drawn from the run's seed."),
        ],
        "round": [
            _DYNAMICS.get(about["dynamics"], "A player picks one of its legal moves."),
            "The state updates, and play goes on until the game reaches a terminal state.",
        ],
        "win": [pay_line, "The final returns come straight from OpenSpiel."],
        "agents": [
            "Each turn the agent gets a text rendering of its view of the state and every legal move with its number and label.",
            "It answers with one JSON action naming a move; a reply that still fails to parse after retries plays the lowest legal move, flagged as a fallback.",
        ],
        "watch_for": watch,
        "runs": [{"id": r} for r in rec["_run_ids"]],
    }


def _add_to_site(ids: list[str]) -> None:
    path = CONTENT / "site.yaml"
    text = path.read_text(encoding="utf-8")
    listed = set(re.findall(r"^  - ([a-z][a-z0-9_]*)\s*$", text.split("\ngames:\n", 1)[-1], re.M))
    new = [i for i in ids if i not in listed]
    if new:
        path.write_text(text.rstrip("\n") + "\n" + "".join(f"  - {i}\n" for i in new), encoding="utf-8")
    print(f"content/site.yaml: added {len(new)} game(s)")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--demo", type=Path, default=ROOT.parent / "social_game_env" / "demo")
    parser.add_argument("--force", action="store_true", help="rewrite files this tool generated before")
    args = parser.parse_args()
    index = json.loads((args.demo / "index.json").read_text(encoding="utf-8"))
    written, listed = 0, []
    for gid, game in sorted(index["games"].items()):
        if game["engine"] != "training" or not game["runs"]:
            continue
        rec = json.loads((args.demo / gid / game["runs"][0]["id"] / "run.json").read_text(encoding="utf-8"))
        path = CONTENT / "games" / f"{gid}.yaml"
        if path.exists():
            listed.append(gid)
            if not (args.force and path.read_text(encoding="utf-8").startswith(GENERATED_MARK)):
                continue
        if not rec["extras"].get("about"):
            print(f"  skip {gid}: no `about` facts; write content/games/{gid}.yaml by hand")
            continue
        body = content_for(gid, {**rec, **rec["extras"], "_run_ids": [r["id"] for r in game["runs"]]})
        head = (f"{GENERATED_MARK} from the recorded run. Delete this line before editing,\n"
                "# or --force will overwrite the file. Field reference: templates/game/content.yaml.\n")
        path.write_text(head + yaml.safe_dump(body, sort_keys=False, allow_unicode=True, width=100), encoding="utf-8")
        written += 1
        listed.append(gid)
    print(f"wrote {written} content file(s)")
    _add_to_site(listed)


if __name__ == "__main__":
    sys.exit(main())
